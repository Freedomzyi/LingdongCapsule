using Capsule.Core;
var now = DateTimeOffset.UtcNow;
var s = new IslandState();
void Check(bool ok, string message) { if (!ok) throw new Exception(message); Console.WriteLine("PASS " + message); }
Check(s.Mode == IslandMode.Clock, "Initial clock");
s.UpdateMedia(new("A", "Artist", true, true));
s.Show(new("app", "App", "Title", "Body"), now);
s.UpdateMedia(new("B", "Artist", true, true));
Check(s.Mode == IslandMode.Notification, "Notification retains priority during track change");
s.Tick(now.AddSeconds(7));
Check(s.Mode == IslandMode.Media && s.Media.Title == "B", "Resume latest track, not old frame");
s.Show(new("app", "App", "Title", "Body"), now);
s.UpdateMedia(new("B", "Artist", false, true)); s.Dismiss();
Check(s.Mode == IslandMode.Clock && s.Media.Available, "Pause during notification returns clock with controls available");
s.Show(new("app", "App", "Title", "Body"), now); s.Expand(now.AddSeconds(5)); s.Tick(now.AddSeconds(7));
Check(s.Notification is not null && s.Expanded, "Expanded notice has extended deadline");
s.UpdateMedia(new("", "", false, false)); s.Tick(now.AddSeconds(26));
Check(s.Mode == IslandMode.Clock && !s.Media.Available, "Player exit and notification timeout");
s.Show(new("a", "A", "1", ""), now); s.Show(new("b", "B", "2", ""), now.AddSeconds(3)); s.Tick(now.AddSeconds(7));
Check(s.Notification?.App == "B" && !s.Expanded, "New notification replaces old one with fresh timeout");
s.Tick(now.AddDays(1)); Check(s.Mode == IslandMode.Clock, "Wake after expiration");

var lyrics=LyricsDocument.Parse("[00:01.00]Alpha\n[00:03.50][00:05.00]Beta","[00:01.00]One\n[00:03.50]Two");
Check(lyrics.Lines.Count==3 && lyrics.At(TimeSpan.FromMilliseconds(900)).Line is null,"LRC multiple time tags and initial silence");
Check(lyrics.At(TimeSpan.FromMilliseconds(1500)).Line?.Translation=="One","Translation matched by time");
Check(Math.Abs(lyrics.At(TimeSpan.FromMilliseconds(2250)).Progress-0.5)<0.001,"Line progress is based on playback time");
Check(lyrics.At(TimeSpan.FromMilliseconds(900),0.2).Line?.Text=="Alpha","User lyric offset advances line selection");
var words=LyricsDocument.Parse("[00:01.00]Alpha Beta",wordTiming:"[1000,2000](1000,1000,0)Alpha (2000,1000,0)Beta");
Check(words.HasWordTiming && words.Lines[0].Words.Count==2,"Time-before-text YRC parsed");
var suffix=LyricsDocument.Parse("[00:01.00]AlphaBeta",wordTiming:"[1000,2000]Alpha(1000,1000)Beta(2000,1000)");
Check(suffix.HasWordTiming && suffix.Lines[0].Words[1].StartMs==2000,"Text-before-time word timing parsed");
var mismatch=LyricsDocument.Parse("[00:01.00]Original",wordTiming:"[1000,2000](1000,1000,0)Wrong");
Check(!mismatch.HasWordTiming,"Different lyric version does not acquire incorrect word timing");
s.MediaClockSwitch=false;s.UpdateMedia(new("Paused","Artist",false,true));Check(s.Mode==IslandMode.Media,"Disabling media-clock switch retains paused media");
s.MediaClockSwitch=true;Check(s.Mode==IslandMode.Clock,"Re-enabling media-clock switch returns paused clock");

s.Dismiss();s.Show(new("app","App","First","",1),now);s.Expand(now.AddSeconds(1));s.Show(new("APP","App","Latest","",2),now.AddSeconds(2));
Check(s.GroupCount==2 && s.LastNoticeGrouped && s.Notification?.Title=="Latest" && !s.Expanded,"Distinct same-source notices merge and reset reader to latest content");
s.Show(new("app","App","Updated","",2),now.AddSeconds(3));Check(s.GroupCount==1 && !s.LastNoticeGrouped,"Updating the same notification ID does not increment group count");
s.Show(new("other","Other","Other","",3),now.AddSeconds(4));Check(s.GroupCount==1 && !s.LastNoticeGrouped,"Different sources do not merge");
s.Show(new("other","Other","After expiry","",4),now.AddSeconds(11));Check(s.GroupCount==1 && !s.LastNoticeGrouped,"Expired notice does not merge into new notification");
s.GroupNotifications=false;s.Show(new("other","Other","Ungrouped","",5),now.AddSeconds(12));Check(s.GroupCount==1 && !s.LastNoticeGrouped,"Grouping preference is respected");
s.SetQuietUntil(now.AddMinutes(30),now.AddSeconds(13));Check(s.Notification==null && !s.Show(new("app","App","Muted","",6),now.AddMinutes(1)),"Quiet period dismisses overlay and rejects incoming notices");
s.Tick(now.AddMinutes(31));Check(s.Notification==null && !s.IsQuiet(now.AddMinutes(31)),"Quiet expiry does not replay muted notices");
Check(s.Show(new("app","App","New","",7),now.AddMinutes(31)) && s.GroupCount==1,"New notices resume after quiet expiry");
